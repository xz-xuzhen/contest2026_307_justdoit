/****************************************************************************
 * reminder_engine.h — 课程提醒引擎
 *
 * 功能：
 *   - 后台线程每 60 秒检查课程表
 *   - 距上课 ≤ remind_min 分钟时触发提醒
 *   - 震动三短震 + LVGL 弹窗
 *   - 避免重复提醒
 *
 * Contest 2026 Team 307
 ****************************************************************************/

#ifndef __REMINDER_ENGINE_H
#define __REMINDER_ENGINE_H

/****************************************************************************
 * 公共 API
 ****************************************************************************/

/**
 * 启动提醒引擎（创建后台线程）
 * @return 0 成功, -1 失败
 */

int reminder_engine_start(void);

/**
 * 停止提醒引擎
 */

void reminder_engine_stop(void);

/**
 * 查询引擎运行状态
 * @return 1 运行中, 0 已停止
 */

int reminder_engine_is_running(void);

/**
 * 手动触发一次提醒测试（调试用）
 * 震动 + 弹窗，用于验证硬件是否正常
 */

int reminder_engine_test(void);

#endif /* __REMINDER_ENGINE_H */
