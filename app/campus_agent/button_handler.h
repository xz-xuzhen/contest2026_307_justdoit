/****************************************************************************
 * button_handler.h — 按键快捷键处理
 *
 * 功能：
 *   - KEY1 短按：开关课程提醒
 *   - KEY2 短按：开关久坐监测
 *   - KEY1 长按：刷新课程列表
 *   - KEY2 长按：显示今日简报
 *
 * Contest 2026 Team 307
 ****************************************************************************/

#ifndef __BUTTON_HANDLER_H
#define __BUTTON_HANDLER_H

/****************************************************************************
 * 按键回调函数类型
 ****************************************************************************/

typedef void (*button_cb_t)(int key, int is_long_press);

/**
 * key: 1=KEY1, 2=KEY2
 * is_long_press: 0=短按, 1=长按
 */

/****************************************************************************
 * 公共 API
 ****************************************************************************/

/**
 * 启动按键监听线程
 *
 * @param cb 按键事件回调函数
 * @return 0 成功, -1 失败
 */

int button_handler_start(button_cb_t cb);

/**
 * 停止按键监听
 */

void button_handler_stop(void);

/**
 * 查询按键监听状态
 * @return 1 运行中, 0 已停止
 */

int button_handler_is_running(void);

#endif /* __BUTTON_HANDLER_H */
